#!/usr/bin/env python3
"""Bake the HUD's ASCII font atlas from Liberation Mono Bold."""
from pathlib import Path
import argparse

import numpy as np
from PIL import Image, ImageDraw, ImageFont
from scipy.ndimage import distance_transform_edt

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('font', type=Path, help='Path to LiberationMono-Bold.ttf')
args = parser.parse_args()

atlas = np.zeros((256, 512), dtype=np.uint8)
supersample = 4
font = ImageFont.truetype(str(args.font), 43 * supersample)
for code in range(33, 127):
    glyph = Image.new('L', (32 * supersample, 40 * supersample))
    draw = ImageDraw.Draw(glyph)
    draw.text((3 * supersample, 30.5 * supersample), chr(code), anchor='ls', font=font, fill=255)
    ink = np.asarray(glyph) >= 128
    signed = distance_transform_edt(ink) - distance_transform_edt(~ink)
    sdf = np.clip(127.5 + (signed - 0.5 * np.sign(signed)) * (127.5 / (5 * supersample)), 0, 255)
    sampled = Image.fromarray(sdf.astype(np.uint8)).resize((32, 40), Image.Resampling.BOX)
    column, row = (code - 32) % 16, (code - 32) // 16
    atlas[row * 40:(row + 1) * 40, column * 32:(column + 1) * 32] = np.asarray(sampled)

# Each packet holds either a literal span or a run of zero-valued texels.
pixels = atlas.tobytes()
packed = bytearray()
offset = 0
while offset < len(pixels):
    end = offset + 1
    is_zero = pixels[offset] == 0
    while end < len(pixels) and end - offset < 128 and (pixels[end] == 0) == is_zero:
        end += 1
    packed.append((0 if is_zero else 128) + end - offset - 1)
    if not is_zero:
        packed.extend(pixels[offset:end])
    offset = end

path = Path(__file__).resolve().parents[1] / 'engine/src/ui_font_atlas.inc'
with path.open('w') as output:
    output.write('// Generated by scripts/generate-ui-font.py. See third_party/ui_font/OFL.txt.\n')
    for offset in range(0, len(packed), 24):
        output.write('    ' + ','.join(map(str, packed[offset:offset + 24])) + ',\n')
