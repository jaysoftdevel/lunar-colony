#!/usr/bin/env python3
"""Generate the small temporal confidence model. Requires NumPy for training only."""

from pathlib import Path
import numpy as np


def observations(rng, count):
    geometry_error = rng.random(count)
    sigma = rng.uniform(.011, .29, count)
    detail = rng.random(count)
    stale = rng.random(count) < (.05 + .68 * geometry_error ** 2)
    lighting_change = rng.normal(0, .29, count) * stale
    current_noise = rng.normal(0, 1, count) * sigma
    old_noise = rng.normal(0, 1, count) * sigma * .51
    difference = np.abs(lighting_change + old_noise - current_noise)
    x = np.stack((geometry_error, np.minimum(difference / np.maximum(.045, 3.0 * sigma), 1),
                  np.minimum(sigma / .29, 1), detail), axis=1)
    previous_error = (sigma * .51) ** 2 + lighting_change ** 2 + .042 * geometry_error ** 3 * detail
    optimal = sigma ** 2 / (sigma ** 2 + previous_error)
    return x.astype(np.float32), np.clip(optimal, .04, .90).astype(np.float32)


def main():
    rng = np.random.default_rng(1729)
    x, target = observations(rng, 26000)
    w = rng.normal(0, .37, (4, 8))
    b = np.zeros(8)
    out = rng.normal(0, .20, 8)
    bias = 0.
    def sigmoid(x):
        return 1 / (1 + np.exp(-np.clip(x, -20, 20)))
    for epoch in range(84):
        rate = .12 * (1 - .53 * epoch / 84)
        for indices in np.array_split(rng.permutation(len(x)), 51):
            inputs = x[indices]
            hidden = np.tanh(inputs @ w + b)
            y = sigmoid(hidden @ out + bias)
            error = (y - target[indices]) * y * (1 - y) / len(indices)
            delta = error[:, None] * out * (1 - hidden * hidden)
            out -= rate * (hidden.T @ error)
            bias -= rate * error.sum()
            w -= rate * (inputs.T @ delta)
            b -= rate * delta.sum(axis=0)
    test, expected = observations(rng, 4600)
    mse = np.mean((sigmoid(np.tanh(test @ w + b) @ out + bias) - expected) ** 2)
    print(f"Temporal confidence validation MSE {mse:.5f}")
    vector = lambda a: "vec4(" + ",".join(f"{value:.8f}" for value in a) + ")"
    vectors = ",\n        ".join(vector(v) for v in w.T)
    biases = ",".join(f"{v:.8f}" for v in b)
    outputs = ",".join(f"{v:.8f}" for v in out)
    source = f"""#pragma once

namespace eng::lunar_shaders {{

// Generated by scripts/train-ray-filter.py.
inline constexpr const char* learned_filter=R"GLSL(
float learnedConfidence(vec4 features){{
    const vec4 weights[8]=vec4[8](
        {vectors});
    const float biases[8]=float[8]({biases});
    const float coefficients[8]=float[8]({outputs});
    float score={bias:.8f};
    for(int i=0;i<8;++i) score+=tanh(dot(features,weights[i])+biases[i])*coefficients[i];
    return 1.0/(1.0+exp(-score));
}}
)GLSL";

}} // namespace eng::lunar_shaders
"""
    path = Path(__file__).resolve().parents[1] / "engine" / "src" / "lunar_learned_filter.hpp"
    path.write_text(source)


if __name__ == "__main__":
    main()
